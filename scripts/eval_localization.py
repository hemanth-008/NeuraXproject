"""Evaluate heatmap faithfulness and labeled classical-CV pseudo-ground truth.

The masks in this report are explicitly pseudo-GT: the project has image-level
labels only.  No locked-holdout row is accepted by this script.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np


def _assert_no_holdout(frame: Any) -> Any:
    if "source_split" in frame.columns:
        split = frame["source_split"].astype(str).str.lower()
        assert not bool(split.isin({"holdout", "locked", "locked_holdout", "locked-holdout"}).any()), "holdout rows reached localization evaluation"
    return frame


def otsu_mask(image: np.ndarray) -> np.ndarray:
    data = np.clip(image, 0, 255).astype(np.uint8)
    hist = np.bincount(data.ravel(), minlength=256).astype(np.float64)
    total = max(1, data.size)
    cumulative = np.cumsum(hist)
    cumulative_mean = np.cumsum(hist * np.arange(256))
    total_mean = cumulative_mean[-1]
    denom = cumulative * (total - cumulative)
    score = np.divide((total_mean * cumulative - cumulative_mean) ** 2, denom, out=np.zeros(256), where=denom > 0)
    return data >= int(np.argmax(score))


def _auc(values: list[float]) -> float:
    if len(values) < 2:
        return float(values[0]) if values else 0.0
    x = np.linspace(0.0, 1.0, len(values))
    return float(np.trapezoid(np.asarray(values, dtype=np.float64), x))


def _image_path(value: Any, root: Path) -> Path | None:
    path = Path(str(value))
    candidates = [path, root / path, root / "data" / path]
    for candidate in candidates:
        if candidate.exists():
            return candidate.resolve()
    return None


def _read_heatmap(value: Any) -> np.ndarray | None:
    if value is None or str(value) in {"", "None", "nan"}:
        return None
    path = Path(str(value))
    if not path.exists():
        return None
    from PIL import Image

    with Image.open(path) as image:
        rgb = np.asarray(image.convert("RGB"), dtype=np.float32) / 255.0
    # Overlay red channel is the stable heat signal generated by infer.py.
    heat = rgb[..., 0] - rgb[..., 2] * 0.25
    heat -= float(heat.min())
    maximum = float(heat.max())
    return heat / maximum if maximum > 1e-8 else np.zeros_like(heat)


def _faithfulness(engine: Any, path: Path, heatmap: np.ndarray, class_index: int, torch: Any) -> tuple[float, float]:
    from src.vision.infer import preprocess_image

    array, _ = preprocess_image(path)
    order = np.argsort(heatmap.ravel())[::-1]
    fractions = np.linspace(0.0, 1.0, 6)
    deletion: list[float] = []
    insertion: list[float] = []
    baseline = np.zeros_like(array)
    # Use normalized gray background rather than an image-derived target.
    baseline[:] = (0.449 / 0.226)
    for fraction in fractions:
        count = int(round(float(fraction) * len(order)))
        keep = np.zeros(array.shape[1] * array.shape[2], dtype=bool)
        keep[order[:count]] = True
        keep = keep.reshape(array.shape[1:])
        deleted = array.copy()
        deleted[:, keep] = baseline[:, keep]
        inserted = baseline.copy()
        inserted[:, keep] = array[:, keep]
        del_out = engine.predict_array(deleted, class_for_cam=class_index)
        ins_out = engine.predict_array(inserted, class_for_cam=class_index)
        deletion.append(float(del_out["class_probs"][class_index]))
        insertion.append(float(ins_out["class_probs"][class_index]))
    # Higher insertion and lower deletion are desirable.  Report their AUCs
    # exactly as measured, without claiming human-localization accuracy.
    return _auc(deletion), _auc(insertion)


def evaluate(predictions_path: Path, output_path: Path, repo_root: Path, sample_size: int = 300) -> dict[str, Any]:
    import pandas as pd

    frame = _assert_no_holdout(pd.read_parquet(predictions_path))
    if "source_split" in frame.columns:
        frame = frame[~frame["source_split"].astype(str).str.lower().isin({"holdout", "locked", "locked_holdout", "locked-holdout"})]
    frame = frame.head(int(sample_size)).copy()
    if not len(frame):
        raise RuntimeError("no non-holdout prediction rows available for localization evaluation")
    # Importing the engine enforces the same model/calibration prerequisites as infer.
    from src.vision.infer import InferenceEngine, preprocess_image

    engine = InferenceEngine(repo_root / "artifacts", repo_root=repo_root)
    pointing: list[float] = []
    ious: list[float] = []
    deletion: list[float] = []
    insertion: list[float] = []
    used = 0
    for _, row in frame.iterrows():
        path = _image_path(row.get("image_path", row.get("file")), repo_root)
        if path is None:
            continue
        heat = _read_heatmap(row.get("heatmap_path"))
        if heat is None:
            array, _ = preprocess_image(path)
            heat = engine.predict_array(array)["heatmap"]
        from PIL import Image

        with Image.open(path) as image:
            gray = np.asarray(image.convert("L").resize((256, 256)), dtype=np.uint8)
        pseudo = otsu_mask(gray)
        resized_heat = np.asarray(Image.fromarray(np.uint8(np.clip(heat, 0, 1) * 255)).resize((256, 256)), dtype=np.float32) / 255.0
        peak = np.unravel_index(int(np.argmax(resized_heat)), resized_heat.shape)
        pointing.append(float(pseudo[peak]))
        threshold = float(np.quantile(resized_heat, 0.90))
        pred = resized_heat >= threshold
        intersection = np.logical_and(pred, pseudo).sum()
        union = np.logical_or(pred, pseudo).sum()
        ious.append(float(intersection / union) if union else 0.0)
        class_index = list(("crack", "hole", "normal", "rust", "scratch")).index(str(row.get("pred_family", "normal"))) if str(row.get("pred_family", "normal")) in {"crack", "hole", "normal", "rust", "scratch"} else 2
        deletion_auc, insertion_auc = _faithfulness(engine, path, resized_heat, class_index, engine.torch)
        deletion.append(deletion_auc)
        insertion.append(insertion_auc)
        used += 1
    if not used:
        raise RuntimeError("none of the sampled prediction rows reference readable images")
    result = {
        "meta": {"generated_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(), "source": str(predictions_path), "assumption_ids": ["D13", "D19", "D26"], "tag": "ADVISORY"},
        "n": used,
        "method": "Grad-CAM++ deletion/insertion plus Otsu pseudo-GT",
        "deletion_auc": float(np.mean(deletion)),
        "insertion_auc": float(np.mean(insertion)),
        "pointing_game_hit_rate": float(np.mean(pointing)),
        "iou_mean": float(np.mean(ious)),
        "caveats": ["pseudo-GT is generated by classical CV (Otsu), not human labels", "association, not proven causation", "locked holdout excluded"],
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--predictions", default="artifacts/predictions.parquet")
    parser.add_argument("--output", default="artifacts/localization.json")
    parser.add_argument("--sample-size", type=int, default=300)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    result = evaluate(Path(args.predictions), Path(args.output), root, args.sample_size)
    print(json.dumps({key: result[key] for key in ("n", "deletion_auc", "insertion_auc", "pointing_game_hit_rate", "iou_mean")}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
